#area and circumfrence of circle
class Circle:
    
    def __init__(self,radius):
        self.radius = radius
        
    def area(self):
        area = ((22/7)*self.radius * self.radius) 
        print("area of circle is ",area)
        
    def circumfrence(self):
        circumfrence = (2 * (22/7) * self.radius) 
        print("Circumfrence of circle is",circumfrence)  
        
    
    
c1 = Circle(21)
c1.area()
c1.circumfrence()




